    counts = collections.OrderedDict()
    for kind in ('melee', 'firearm', 'food', 'clothing', 'container', 'recipes', 'vehicles'):
        got = collections.Counter(cell(l, 1).strip('`') for _s, l in rows_by_kind[kind])
        exp = expected_rows[kind]
        missing = sorted(set(exp) - set(got))
        extra = sorted(set(got) - set(exp))

def tree_hash(root):
    h = hashlib.sha256()
    for dp, dn, fn in sorted(os.walk(root)):
        dn.sort()
        for f in sorted(fn):
            p = os.path.join(dp, f)
            h.update(os.path.relpath(p, root).replace(os.sep, '/').encode())
            with open(p, 'rb') as fh:
                h.update(fh.read())
    return h.hexdigest()



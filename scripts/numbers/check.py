def read_lines(path):
    with open(path, encoding='utf-8-sig', errors='replace', newline='') as f:
        return f.read().replace('\r\n', '\n').replace('\r', '\n').split('\n')


def parse_page(path):
    with open(path, encoding='utf-8', newline='') as f:
        text = f.read()
    if '\r' in text:
        err('%s: carriage return in file' % path)
    if not text.startswith('---\n'):
        err('%s: no frontmatter' % path)
        return {}, text
    end = text.index('\n---\n', 4)
    fm = {}
    key = None
    for line in text[4:end].split('\n'):
        m = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if m:
            key = m.group(1)
            v = m.group(2)
            if v == '':
                fm[key] = []
            else:
                fm[key] = json.loads(v) if v.startswith('"') else v.strip("'")
        elif line.startswith('  - ') and key:
            fm[key].append(line[4:])
    return fm, text[end + 5:]


# ---------------------------------------------------------------- independent counts from raw files

HDR = re.compile(r'^\s{0,8}(item|craftRecipe|vehicle|template vehicle|entity|recipe|fixing|evolvedrecipe|uniquerecipe|model|sound|animation)\s+(\S+)\s*$')
FIELD = re.compile(r'^\s+([A-Za-z_!]+)\s*=\s*([^,]*?)\s*,?\s*$')


def raw_scan(scripts_dir):
    """Line-based scan of every script file. Returns {kind: {name: {field(lower): value}}} and the first line."""
    out = collections.defaultdict(collections.OrderedDict)
    firstline = {}
    for dp, _dn, fn in os.walk(scripts_dir):
        for f in sorted(fn):
            if not f.lower().endswith('.txt'):
                continue
            p = os.path.join(dp, f)
            rel = 'scripts/' + os.path.relpath(p, scripts_dir).replace(os.sep, '/')
            cur = None
            depth_indent = None
            for i, line in enumerate(read_lines(p)):
                m = HDR.match(line)
                if m and (len(line) - len(line.lstrip())) <= 4:
                    kind, name = m.group(1), m.group(2)
                    cur = out[kind].setdefault(name, {})
                    firstline.setdefault((kind, name), (rel, i + 1))
                    depth_indent = len(line) - len(line.lstrip())
                    continue
                if cur is None:
                    continue
                if line.strip() == '}' and (len(line) - len(line.lstrip())) <= (depth_indent or 0):
                    cur = None
                    continue
                if (len(line) - len(line.lstrip())) == (depth_indent or 0) + 4:
                    mf = FIELD.match(line)
                    if mf:
                        cur[mf.group(1).lower()] = mf.group(2)
    return out, firstline


PAIR = re.compile(r'^\s*"([^"]+)"\s*,\s*(-?[\d.]+)\s*(?:,\s*\d*)?\s*(?:--.*)?$')


def raw_loot(items_dir):
    """Count entry lines of the loot tables, by plain line matching."""
    proc = []
    for i, line in enumerate(read_lines(os.path.join(items_dir, 'ProceduralDistributions.lua'))):
        m = PAIR.match(line)
        if m:
            proc.append((m.group(1), i + 1))
    clutter = []
    for fn in sorted(os.listdir(items_dir)):
        if re.match(r'Distribution_\w+Junk\.lua$', fn):
            for i, line in enumerate(read_lines(os.path.join(items_dir, fn))):
                m = PAIR.match(line)
                if m:
                    clutter.append((m.group(1), i + 1, fn))
    return proc, clutter


def truthy(v):
    return v is not None and v.strip().lower() == 'true'



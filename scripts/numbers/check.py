    determinism = 'skipped'
    if not a.no_determinism:
        here = os.path.dirname(os.path.abspath(__file__))
        tmp = tempfile.mkdtemp(prefix='numbers-check-')
        try:
            hashes = []
            for i in range(2):
                d = os.path.join(tmp, 'r%d' % i, 'numbers-tables')
                os.makedirs(os.path.dirname(d))
                r = subprocess.run([sys.executable, '-B', '-I', os.path.join(here, 'generate.py'), '--capture', a.capture, '--out', d],
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                if r.returncode != 0:
                    err('generator failed in the determinism run: %s' % r.stderr.decode('utf-8', 'replace')[-300:])
                    break
                hashes.append(tree_hash(d))
            if len(hashes) == 2:
                if hashes[0] != hashes[1]:
                    err('two generator runs differ')
                    determinism = 'DIFFERENT'
                else:
                    determinism = 'identical (%s)' % hashes[0][:12]
                if hashes[0] != tree_hash(a.out):
                    err('the output folder is not what the generator writes now; regenerate it')
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    # report
    total_bytes = sum(os.path.getsize(os.path.join(a.out, f)) for f in os.listdir(a.out))
    print('pages: %d; internal links checked: %d; Java cites checked: %d; existing articles scanned: %d' % (len(pages), nlinks, java_checked, len(existing)))
    print('%-10s %9s %9s  %s' % ('table', 'expected', 'in pages', 'left out (independent count)'))
    for k, v in counts.items():
        print('%-10s %9d %9d  %s' % (k, v[0], v[1], v[2] or ''))
    largest = max(pages.values(), key=lambda p: p['words'])
    print('largest page: %s (%d words, limit %d)' % (largest['file'], largest['words'], MAX_WORDS))
    print('total size: %.1f MB; determinism: %s' % (total_bytes / 1048576.0, determinism))
    if errors:
        print('FAIL: %d problems' % len(errors))
        for e in errors[:60]:
            print('  [ERROR] ' + e)
        if len(errors) > 60:
            print('  ... %d more' % (len(errors) - 60))
        sys.exit(1)
    print('PASS')



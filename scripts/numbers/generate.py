def read_loot(server_dir):
    items_dir = os.path.join(server_dir, 'Items')
    stm = lp.parse_file(os.path.join(items_dir, 'ProceduralDistributions.lua'), True)
    lists = None
    for n, v, _l in stm:
        if n == 'ProceduralDistributions.list':
            lists = v
    if lists is None:
        raise SystemExit('ProceduralDistributions.list not found')
    if lists.dup:
        DUPKEYS.append('ProceduralDistributions.list sets these list names twice: %s' % ', '.join(sorted(set(lists.dup))))
    for k, v, ln in lists.keys:
        if isinstance(v, lp.Table):
            for sub in [v] + [x for _k, x, _l in v.keys if isinstance(x, lp.Table)]:
                if sub.dup:
                    DUPKEYS.append('list %s (line %d) sets %s twice' % (k, ln, ', '.join(sorted(set(sub.dup)))))
    clutter = {}
    for fn in sorted(os.listdir(items_dir)):
        if re.match(r'Distribution_\w+Junk\.lua$', fn):
            for n, v, ln in lp.parse_file(os.path.join(items_dir, fn), True):
                if n.startswith('ClutterTables.') and isinstance(v, lp.Table):
                    if v.dup:
                        DUPKEYS.append('%s (%s:%d) sets %s twice' % (n, fn, ln, ', '.join(sorted(set(v.dup)))))
                    clutter[n[len('ClutterTables.'):]] = (v, fn, ln)
    return lists, clutter


def entries_of(tbl, clutter):
    """Return (rolls, [(item, chance, line)]) of a table holding rolls and items."""
    it = tbl.get('items')
    if isinstance(it, lp.Ref):
        key = it.name.split('.', 1)[1]
        src = clutter[key][0]
        pos = src.pos
        line_file = clutter[key][1]
    elif isinstance(it, lp.Table):
        pos = it.pos
        line_file = None
    else:
        return tbl.get('rolls'), [], None
    vals = [p for p in pos]
    if len(vals) % 2:
        # a stray value after the last pair (vanilla has one: `"Jacket_WhiteTINT", 10,7`). Loot is read in
        # (name, chance) pairs, so the lone value is not an entry; it is reported, not hidden.
        ANOMALIES.append('items table near line %d ends with a lone value %r at line %d; ignored' % (vals[0][1], vals[-1][0], vals[-1][1]))
        vals = vals[:-1]
    out = []
    for i in range(0, len(vals), 2):
        name, ln = vals[i]
        ch, _l2 = vals[i + 1]
        if not isinstance(name, str) or not isinstance(ch, (int, float)):
            raise SystemExit('unexpected loot entry near line %d' % ln)
        out.append((name, ch, ln))
    return tbl.get('rolls'), out, line_file


def build_spawn_table(lists, clutter, names, scripts):
    PD = 'media/lua/server/Items/ProceduralDistributions.lua'
    by_item = collections.OrderedDict()
    n_lists = 0
    n_entries = 0
    n_alias = 0
    clutter_used = collections.Counter()
    refs_seen = set()

    def add(item, label, role, chance, rolls, file, line):
        by_item.setdefault(item, []).append((label, role, chance, rolls, file, line))

    for lname, tbl, lline in lists.keys:
        if isinstance(tbl, lp.Ref):
            n_alias += 1          # NAME = OtherName inside the constructor reads a global that is nil
            continue
        if not isinstance(tbl, lp.Table):
            raise SystemExit('list %s is not a table' % lname)
        n_lists += 1
        rolls, ents, _f = entries_of(tbl, clutter)
        for it, ch, ln in ents:
            add(it, lname, 'items', ch, rolls, PD, ln)
            n_entries += 1
        junk = tbl.get('junk')
        if isinstance(junk, lp.Table):
            jr, jents, _f = entries_of(junk, clutter)
            for it, ch, ln in jents:
                add(it, lname, 'junk', ch, jr, PD, ln)
                n_entries += 1
        elif isinstance(junk, lp.Ref):
            clutter_used[junk.name] += 1
            refs_seen.add(junk.name)
    clutter_entries = 0
    CF = 'media/lua/server/Items/'
    for jname in sorted(refs_seen):
        key = jname.split('.', 1)[1]
        tbl, fn, ln0 = clutter[key]
        rolls, ents, _f = entries_of(tbl, clutter)
        itname = tbl.get('items').name.split('.', 1)[1]
        src_tbl, src_fn, _l = clutter[itname]
        # the entries sit in the XItems table; cite that table's lines
        _r, ents2, _f = entries_of(tbl, clutter)
        for it, ch, ln in ents2:
            add(it, jname + ' (junk list used by %d lists)' % clutter_used[jname], 'junk', ch, rolls, CF + src_fn, ln)
            clutter_entries += 1
    rows = []
    unknown = 0
    for item, ents in by_item.items():
        sc = scripts.get(item)
        if sc is None:
            unknown += 1
            nm = clean(item)
            idc = code(item) + ' (no item script)'
        else:
            nm = names.name_of(sc)
            idc = code(item)
        parts = []
        cites = collections.OrderedDict()
        for label, role, chance, rolls, file, line in sorted(ents, key=lambda e: (e[0].lower(), e[1], e[5])):
            r = '' if rolls is None else ', rolls %s' % num_fmt(rolls)
            parts.append('%s %s%s%s' % (clean(label), num_fmt(chance), ' junk' if role == 'junk' else '', r))
            cites.setdefault(file, []).append(line)
        cite_txt = '; '.join('%s:%s' % (f, ','.join(str(x) for x in ls)) for f, ls in cites.items())
        rows.append((nm.lower(), item, '| %s | %s | %d | %s | %s |' % (nm, idc, len(ents), '; '.join(parts), code(cite_txt))))
    rows.sort(key=lambda r: (r[0], r[1]))
    rows = [r[2] for r in rows]
    total_entries = n_entries + clutter_entries
    return rows, {'lists': n_lists, 'entries': total_entries, 'procedural_entries': n_entries,
                  'clutter_lists': len(refs_seen), 'clutter_entries': clutter_entries, 'items': len(by_item),
                  'aliases': n_alias, 'unknown': unknown}



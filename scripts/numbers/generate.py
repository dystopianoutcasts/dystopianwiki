def write_all(out):
    if os.path.isdir(out):
        if os.path.basename(os.path.normpath(out)) != CATEGORY:
            sys.exit('refusing to clear %s (not a folder named %s)' % (out, CATEGORY))
        shutil.rmtree(out)
    os.makedirs(out)
    with open(os.path.join(out, '_category.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'name': 'The Numbers Tables',
                   'description': 'Lookup tables generated from the Build 42.22 scripts: weapons, food, clothing, containers, recipes, loot lists and vehicles.',
                   'icon': 'database', 'displayOrder': 2}, f, indent=2)
        f.write('\n')
    slugset = [p['slug'] for p in PAGES]
    total = 0
    for p in PAGES:
        fm = ['---', 'id: build-42-%s' % p['slug'], 'slug: %s' % p['slug'], 'title: %s' % yq(p['title']),
              'game: pz', 'version: build-42', 'section: %s' % SECTION, 'category: %s' % CATEGORY,
              'difficulty: intermediate', 'tags:'] + ['  - %s' % t for t in p['tags']] + [
            'excerpt: %s' % yq(p['excerpt']), "last_updated: '%s'" % LAST_UPDATED]
        rel = []
        for s in p['rel']:
            if s in slugset and s != p['slug'] and s not in rel:
                rel.append(s)
        if rel:
            fm.append('related_articles:')
            fm += ['  - %s' % s for s in rel[:8]]
        fm.append('---')
        text = '\n'.join(fm) + '\n' + p['body'].rstrip() + '\n'
        with open(os.path.join(out, p['slug'] + '.md'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        total += len(text.encode('utf-8'))
    return total



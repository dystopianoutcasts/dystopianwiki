def apply_capacity_clamp(scripts):
    """Item.DoParam lowers Capacity to int(50 - weight) when it is larger, using the weight read so far."""
    changed = 0
    for sc in scripts.values():
        if sc.f.get('itemtype', '').lower() != 'base:container':
            continue
        w = 1.0
        cap = None
        for k, v in sc.seq:
            try:
                if k == 'weight':
                    w = max(0.0, float(v))
                elif k == 'capacity':
                    c = int(v)
                    if c > 50.0 - w:
                        c = int(50.0 - w)
                    cap = c
            except ValueError:
                pass
        if cap is not None and str(cap) != sc.f.get('capacity'):
            sc.f['capacity'] = str(cap)
            changed += 1
    return changed



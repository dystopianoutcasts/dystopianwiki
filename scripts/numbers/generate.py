# ---------------------------------------------------------------- text helpers


def ascii_text(s):
    s = unicodedata.normalize('NFKD', str(s))
    s = ''.join(c for c in s if ord(c) < 128)
    return s


def clean(s):
    """Plain ASCII, one line, safe inside a Markdown table cell."""
    s = ascii_text(s).replace('\r', ' ').replace('\n', ' ').replace('\t', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    s = s.replace('\\', '/').replace('|', '/').replace('`', "'")
    s = s.replace('<', '(').replace('>', ')')
    return s


def code(s):
    s = clean(s)
    return '`' + s + '`' if s else ''


def words(text):
    return len(text.split())


def yq(s):
    return json.dumps(s, ensure_ascii=True)


def num_text(s):
    return clean(s)


def fmt_count(n):
    return '{:,}'.format(n)



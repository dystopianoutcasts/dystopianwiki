def recipe_item_text(tok, names, scripts):
    out = []
    for e in tok.split(';'):
        e = e.strip()
        if not e:
            continue
        if e == '*':
            out.append('any item')
        elif ':' in e and not e.startswith('Base.') and re.match(r'^[\d.]+:', e):
            amt, it = e.split(':', 1)
            out.append('%s x %s' % (amt, names.item_id_name(it, scripts)))
        elif '.' in e:
            out.append(names.item_id_name(e, scripts))
        else:
            out.append(e)
    uniq = []
    for o in out:
        if o not in uniq:
            uniq.append(o)
    return ' or '.join(uniq)


def render_io(line, names, scripts):
    toks = line.strip().split()
    if not toks:
        return ''
    kind = toks[0].lower()
    prefix = ''
    if kind in ('+', '-'):
        return clean(line)
    if kind == 'item':
        kind_txt = ''
    else:
        kind_txt = kind + ' '
    amt = toks[1] if len(toks) > 1 else '?'
    rest = []
    mods = []
    for t in toks[2:]:
        if t.startswith('['):
            rest.append(recipe_item_text(t.strip('[]'), names, scripts))
        elif t.startswith('tags['):
            rest.append('tag ' + t[5:].rstrip(']').replace(';', ' or '))
        elif t.startswith('mapper:'):
            rest.append('item chosen by mapper ' + t[7:])
        elif t.startswith('mappers['):
            mods.append('mappers ' + t[8:].rstrip(']').replace(';', ', '))
        elif t.startswith('chance:'):
            mods.append('chance ' + t[7:])
        elif t.startswith('mode:'):
            mods.append(t[5:])
        elif t.startswith('flags['):
            mods.append('flags ' + t[6:].rstrip(']').replace(';', ', '))
        elif t.startswith('categories['):
            rest.append('fluid category ' + t[11:].rstrip(']').replace(';', ' or '))
        else:
            if '.' in t and not t.startswith(('mappers', 'shapedIndex')) and '[' not in t and ':' not in t:
                rest.append(names.item_id_name(t, scripts))
            else:
                mods.append(t)
    s = '%s%s x %s' % (kind_txt, amt, ' '.join(rest) if rest else '?')
    if mods:
        s += ' (' + ', '.join(mods) + ')'
    return clean(s)



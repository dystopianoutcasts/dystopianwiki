class Java(object):
    """Reads field defaults and loader lines out of Item.java so every default is cited to its line."""

    def __init__(self, src_dir):
        self.path = os.path.join(src_dir, ITEM_JAVA)
        with open(self.path, encoding='utf-8', errors='replace') as f:
            self.lines = f.read().split('\n')
        self.decl = {}
        rx = re.compile(r'^\s*(?:public |private |protected )?(?:final )?([A-Za-z][\w<>\[\], ]*?) ([A-Za-z_]\w*)(?: = ([^;]+))?;\s*$')
        for i, ln in enumerate(self.lines):
            if i > 1500:
                break
            m = rx.match(ln)
            if m and m.group(2) not in self.decl:
                self.decl[m.group(2)] = (m.group(1), m.group(3), i + 1)
        self.param = {}
        rx2 = re.compile(r'equalsIgnoreCase\("([^"]+)"\)')
        for i, ln in enumerate(self.lines):
            if i < 1900:
                continue
            m = rx2.search(ln)
            if m and 'param.trim()' in ln:
                self.param.setdefault(m.group(1).lower(), i + 1)

    def default(self, field):
        """(default text, line) for an Item field."""
        typ, init, line = self.decl[field]
        if init is None:
            d = {'float': '0.0', 'int': '0', 'boolean': 'false'}.get(typ)
            if d is None:
                d = 'none'
        else:
            d = init.strip()
            d = re.sub(r'(\d)F$', r'\1', d)
        return d, line

    def reads(self, key):
        return self.param[key.lower()]

    def find(self, snippet):
        for i, ln in enumerate(self.lines):
            if snippet in ln:
                return i + 1
        raise SystemExit('Item.java line not found: ' + snippet)


def src_find(root, relpath, snippet, last=False):
    hit = None
    with open(os.path.join(root, relpath), encoding='utf-8', errors='replace') as f:
        for i, ln in enumerate(f.read().split('\n')):
            if snippet in ln:
                hit = i + 1
                if not last:
                    return hit
    if hit:
        return hit
    raise SystemExit('%s: line not found: %s' % (relpath, snippet))



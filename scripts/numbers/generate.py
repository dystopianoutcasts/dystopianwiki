class Script(object):
    """One script object after the engine's merge of every block with the same name."""

    def __init__(self, name):
        self.name = name
        self.sites = []            # [(relpath, line)]
        self.seq = []              # [(lowerkey, value)] in load order
        self.f = {}                # lowerkey -> value (the last one wins)
        self.blocks = []
        self.enabled = True
        self.debug_only = False

    def add(self, rel, block):
        self.sites.append((rel, block.line))
        self.blocks.append(block)


def engine_split(s):
    """Item.Load and VehicleScript.Load split a value line on every '=' and use parts 0 and 1."""
    parts = s.split('=')
    if len(parts) < 2:
        return None
    return parts[0].strip(), parts[1].strip()


def build_scripts(entries, strict_split=True):
    """Merge blocks that share a name in load order, as ScriptBucket does: the later body is applied on top
    of the earlier one, key by key (BaseScriptObject.reset() does nothing, so nothing is cleared)."""
    out = collections.OrderedDict()
    bad = []
    for mod, name, rel, b in entries:
        sc = out.get(name)
        if sc is None:
            sc = Script(name)
            out[name] = sc
        sc.add(rel, b)
        for e in b.elements:
            if e[0] != 'v':
                continue
            s = e[1]
            if not s.strip():
                continue
            kv = engine_split(s)
            if kv is None:
                bad.append((name, rel, e[3], s.strip()))
                continue
            k, v = kv
            lk = k.lower()
            sc.seq.append((lk, v))
            sc.f[lk] = v
            if lk == 'enabled' and v:
                sc.enabled = v.lower() == 'true'
            elif lk == 'debugonly' and v:
                sc.debug_only = v.lower() == 'true'
    return out, bad


def site_text(sc):
    return '+'.join('%s:%d' % (r, l) for r, l in sc.sites)


def truthy(v):
    return v is not None and v.strip().lower() == 'true'


# ---------------------------------------------------------------- tables: columns


class Col(object):
    def __init__(self, header, key, java=None, meaning='', verified=True, cite=None, mode='raw'):
        self.header = header
        self.key = key              # script key, lower case, or None for a computed column
        self.java = java            # Item field name for the default
        self.meaning = meaning
        self.verified = verified
        self.cite = cite            # extra cite for the meaning
        self.mode = mode


def cell_for(col, sc, J):
    v = sc.f.get(col.key)
    if v is not None and v != '':
        return num_text(v)
    if col.java:
        d, _l = J.default(col.java)
        if d == 'none':
            return '-'
        return d + '*'
    return '-'


def how_to_read(J, cols, extra_bullets, intro):
    L = [':::callout[How to read this table]{kind=key}']
    L.append('- ' + intro)
    L.append('- A value written as `1.5*` is not in the script: it is the engine default, set where the item script class declares the field.')
    L.append('- A dash means the script leaves the field out and the engine has no number for it.')
    for c in cols:
        if c.key is None and not c.meaning:
            continue
        parts = ['**%s**' % c.header]
        if c.key:
            parts.append('(script key `%s`)' % c.key_display)
        bits = []
        if c.meaning:
            bits.append(c.meaning)
        if c.java:
            d, line = J.default(c.java)
            if d == 'none':
                bits.append('No default: the field has no initializer %s.' % java_cite(ITEM_JAVA, line))
            else:
                bits.append('Default when left out: `%s` %s.' % (d, java_cite(ITEM_JAVA, line)))
            bits.append('Read by the loader %s.' % java_cite(ITEM_JAVA, J.reads(c.key_display)))
        if not c.verified:
            bits.append('Meaning not verified.')
        L.append('- ' + ' '.join(parts) + ': ' + ' '.join(bits))
    for b in extra_bullets:
        L.append('- ' + b)
    L.append(':::')
    return '\n'.join(L)


# ---------------------------------------------------------------- page writing


def pack_rows(header, rows, budget=PACK_WORDS, fixed_words=0):
    pages = []
    cur = []
    w = fixed_words
    for r in rows:
        rw = words(r) + 1
        if cur and w + rw > budget:
            pages.append(cur)
            cur = []
            w = fixed_words
        cur.append(r)
        w += rw
    if cur or not pages:
        pages.append(cur)
    return pages


def add_table_pages(slug, title, tags, excerpt_fn, intro_md, header_row, rows, section_title, rel, notes_md=''):
    pre = words(intro_md) + words(header_row) + 80
    chunks = pack_rows(header_row, rows, fixed_words=pre)
    n = len(chunks)
    slugs = [slug if i == 0 else '%s-%d' % (slug, i + 1) for i in range(n)]
    for i, chunk in enumerate(chunks):
        ptitle = title if n == 1 else '%s (part %d of %d)' % (title, i + 1, n)
        body = ['::field-notes', '', SOURCE_LINE, '']
        nav = []
        if n > 1:
            nav.append('Part %d of %d.' % (i + 1, n))
            if i > 0:
                nav.append('[Previous part](%s/%s)' % (BASE_URL, slugs[i - 1]))
            if i < n - 1:
                nav.append('[Next part](%s/%s)' % (BASE_URL, slugs[i + 1]))
        nav.append('[All tables](%s/tbl-index)' % BASE_URL)
        body.append(' | '.join(nav))
        body.append('')
        body.append(intro_md)
        body.append('')
        if notes_md and i == 0:
            body.append(notes_md)
            body.append('')
        body.append('## %s' % section_title)
        body.append('')
        body.append(header_row)
        sep = '|' + '|'.join('---' for _ in header_row.strip('|').split('|')) + '|'
        body.append(sep)
        body.extend(chunk)
        PAGES.append({'slug': slugs[i], 'title': ptitle, 'excerpt': excerpt_fn(len(rows), n, i), 'tags': tags,
                      'body': '\n'.join(body) + '\n', 'rel': [s for s in slugs if s != slugs[i]] + rel})
    return slugs


# ---------------------------------------------------------------- item tables


def item_rows(items, cols, J, names, sort_key=None):
    rows = []
    for sc in items:
        name = names.get(sc.name)
        cells = [name, code(sc.name)] + [cell_for(c, sc, J) for c in cols] + [code(site_text(sc))]
        rows.append((name.lower(), sc.name, '| ' + ' | '.join(cells) + ' |'))
    rows.sort(key=lambda r: (r[0], r[1]))
    return [r[2] for r in rows]


def header_for(cols):
    return '| Name | Id | ' + ' | '.join(c.header for c in cols) + ' | Code |'


def make_item_table(spec, J, scripts, names, ctx):
    """spec: dict(slug, title, itemtype, cols, intro, extra, ...)."""
    cols = spec['cols']
    for c in cols:
        c.key_display = c.key_display if hasattr(c, 'key_display') else (c.key if c.key else '')
    chosen = []
    excluded = collections.Counter()
    total_type = 0
    for sc in scripts.values():
        if sc.f.get('itemtype', '').lower() != spec['itemtype']:
            continue
        if not spec['filter'](sc):
            continue
        total_type += 1
        if truthy(sc.f.get('obsolete')):
            excluded['OBSOLETE = true'] += 1
            continue
        if truthy(sc.f.get('hidden')):
            excluded['Hidden = true'] += 1
            continue
        if not sc.enabled:
            excluded['enabled = false'] += 1
            continue
        if sc.debug_only:
            excluded['debugOnly = true'] += 1
            continue
        chosen.append(sc)
    names_map = {}
    for sc in chosen:
        names_map[sc.name] = names.name_of(sc)
    nm = type('N', (), {'get': staticmethod(lambda k: names_map[k])})
    rows = item_rows(chosen, cols, J, nm)
    header = header_for(cols)
    intro = '\n'.join([
        spec['lede'],
        '',
        how_to_read(J, cols, spec.get('extra', []), spec['intro_bullet'])])
    slugs = add_table_pages(spec['slug'], spec['title'], spec['tags'],
                            spec['excerpt'], intro, header, rows, spec['section_title'], spec.get('rel', []),
                            spec.get('notes_md', ''))
    TABLES.append({'slug': slugs[0], 'slugs': slugs, 'title': spec['title'], 'answers': spec['answers'],
                   'rows': len(chosen), 'excluded': dict(excluded), 'total': total_type, 'kind': spec['kind']})
    return chosen, excluded, total_type


class NameBook(object):
    def __init__(self, item_json, recipe_json, ui_json):
        self.items = item_json
        self.recipes = recipe_json
        self.ui = ui_json
        self.fallback_disp = 0
        self.fallback_id = 0
        self.translated = 0

    def name_of(self, sc):
        full = 'Base.' + sc.name
        t = self.items.get(full)
        if t:
            self.translated += 1
            return clean(t) or sc.name
        d = sc.f.get('displayname')
        if d:
            self.fallback_disp += 1
            return clean(d) or sc.name
        self.fallback_id += 1
        return clean(sc.name)

    def item_id_name(self, item_id, scripts):
        """Name for a Module.Type id that appears in a recipe or a loot list."""
        short = item_id.split('.', 1)[1] if '.' in item_id else item_id
        t = self.items.get('Base.' + short) if (item_id.startswith('Base.') or '.' not in item_id) else self.items.get(item_id)
        if t:
            return clean(t)
        sc = scripts.get(short)
        if sc is not None and sc.f.get('displayname'):
            return clean(sc.f['displayname'])
        return clean(short)


def excerpt_maker(what, extra=''):
    def f(total, n, i):
        s = '%s %s from the Project Zomboid 42.22 scripts, each row with its script line.%s' % (fmt_count(total), what, extra)
        if len(s) > MAX_EXCERPT:
            s = s[:MAX_EXCERPT - 3] + '...'
        return s
    return f



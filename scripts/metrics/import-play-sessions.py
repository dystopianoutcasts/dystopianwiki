"""Import each player's play sessions from the Main server's join/leave logs into aurora.play_sessions.

Reads the logs pulled by pull-user-logs.sh into R:/DystopianOutcasts/_LOCAL/server-logs/Main/ (through
count-playtime.py, which turns "fully connected" / "disconnected player" lines into sessions). Writes a
SQL file of INSERT ... ON CONFLICT DO NOTHING rows (username, started_at, ended_at, source
'server_log') into R:/DystopianOutcasts/_LOCAL/server-logs/ (never the repo), so it is safe to run
again. Only names and times go in: the Steam IDs and IPs in the raw logs are never read into the SQL.

    python -I import-play-sessions.py                 write the SQL file and print the top 10
    python -I import-play-sessions.py --apply         also apply it, then run aurora.metrics_rollup
                                                      over the whole season

Options: --since 2026-10-03 (the season start; sessions are clipped to it), --server outcasts-main.
Run from Git Bash. The Supabase CLI is the 3.1.0 exe by path (the default shim is too old).
"""
import importlib.util
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SERVER_LOGS = Path("R:/DystopianOutcasts/_LOCAL/server-logs")
CLI = "C:/Users/ediaz/scoop/apps/supabase/3.1.0/supabase.exe"
PROJECT = "gwubcipchkwthsorhcky"
BATCH = 500


def load_counter():
    path = Path(__file__).resolve().parent / "count-playtime.py"
    spec = importlib.util.spec_from_file_location("count_playtime", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def clean_name(name):
    """A username as the database keeps it: no control characters, single quotes doubled."""
    return "".join(ch for ch in name if ch.isprintable()).replace("'", "''")


def collect(since):
    counter = load_counter()
    seen = {}
    for name, started, ended, _how in counter.sessions():
        started = max(started, since)
        if ended <= started:
            continue
        seen.setdefault((name, started), ended)  # the same start twice: keep the first
    return sorted(((n, s, e) for (n, s), e in seen.items()), key=lambda r: (r[1], r[0]))


def write_sql(rows, server, out_path):
    lines = [
        "-- Generated by scripts/metrics/import-play-sessions.py: names and times only.",
        "-- Safe to run twice (ON CONFLICT DO NOTHING).",
    ]
    for i in range(0, len(rows), BATCH):
        values = ",\n".join(
            f"  ('{server}', '{clean_name(n)}', '{s.isoformat()}', '{e.isoformat()}', 'server_log')"
            for n, s, e in rows[i : i + BATCH]
        )
        lines.append(
            "INSERT INTO aurora.play_sessions (server_id, username, started_at, ended_at, source) VALUES\n"
            + values
            + "\nON CONFLICT DO NOTHING;"
        )
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_cli(args):
    result = subprocess.run([CLI, "db", "query", f"--remote={PROJECT}", "--yes", *args], cwd=str(Path.home()), capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"supabase CLI failed ({result.returncode}): {result.stdout[-400:]} {result.stderr[-400:]}")
    return result.stdout


def report(rows, since):
    totals = {}
    for n, s, e in rows:
        totals[n] = totals.get(n, 0.0) + (e - s).total_seconds()
    ranked = sorted(totals.items(), key=lambda kv: -kv[1])
    print(f"{len(rows)} sessions, {len(totals)} players, {sum(totals.values()) / 3600:.1f} hours since {since:%Y-%m-%d}")
    print("Top 10 season play time (hours):")
    for n, secs in ranked[:10]:
        print(f"  {n:<24}{secs / 3600:>8.1f}")
    one = totals.get("One")
    if one is not None:
        print(f"One: {one / 3600:.1f} hours ({'more' if one > 2.5 * 3600 else 'not more'} than 2.5 hours)")


def main():
    args = sys.argv[1:]

    def opt(flag, default):
        return args[args.index(flag) + 1] if flag in args else default

    since = datetime.fromisoformat(opt("--since", "2026-10-03")).replace(tzinfo=timezone.utc)
    server = opt("--server", "outcasts-main")
    rows = collect(since)
    out_path = SERVER_LOGS / f"play-sessions-{datetime.now(timezone.utc):%Y-%m-%d}.sql"
    write_sql(rows, server, out_path)
    print(f"wrote {out_path} ({len(rows)} rows)")
    report(rows, since)
    if "--apply" in args:
        run_cli(["-f", str(out_path)])
        run_cli([f"SELECT aurora.metrics_rollup(TIMESTAMPTZ '{since.isoformat()}', now());"])
        print("applied, and rolled up the season")


if __name__ == "__main__":
    main()
